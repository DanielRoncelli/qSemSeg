// ---------------------------------------------------------------------------
// 3. point-to-label mapping
// ---------------------------------------------------------------------------
static void testPointToLabelMapping()
{
	// argmax per subsampled point -> labels, then projected to the original
	// cloud through proj_inds
	std::vector<float> testProbs = {
	    0.1f, 0.8f, 0.1f, // sub 0 -> class 1
	    0.9f,
	    0.05f,
	    0.05f, // sub 1 -> class 0
	    0.2f,
	    0.2f,
	    0.6f, // sub 2 -> class 2
	};
	const std::vector<int> labels = argmaxLabels(testProbs, 3);
	CHECK(labels.size() == 3 && labels[0] == 1 && labels[1] == 0 && labels[2] == 2,
	      "argmaxLabels returns one class index per subsampled point");

	// original -> sub projection: many original points share one sub point
	const std::vector<int64_t> projInds{1, 0, 1, 2, 0};
	std::vector<int>           orig(projInds.size());
	for (size_t i = 0; i < projInds.size(); i++)
	{
		orig[i] = labels[projInds[i]];
	}
	CHECK(orig.size() == 5 && orig[0] == 0 && orig[1] == 1 && orig[2] == 0 && orig[3] == 2 && orig[4] == 1,
	      "every original point receives the label of its projected subsampled point");

	// class index -> dataset label (ParisLille3D: classes 0..8 are labels 1..9,
	// label 0 = 'unclassified' is ignored at training time)
	ModelSpec spec;
	spec.numClasses  = 9;
	spec.labelValues = {1, 2, 3, 4, 5, 6, 7, 8, 9};
	std::string    warning;
	const LabelMap labelMap = buildLabelMap(spec, &warning);
	CHECK(warning.empty(), "no warning when the manifest carries a full label table");
	const std::vector<int> mapped = mapClassIndicesToLabels(labels, labelMap);
	CHECK(mapped.size() == 3 && mapped[0] == 2 && mapped[1] == 1 && mapped[2] == 3,
	      "class indices map to dataset labels (class c -> label c+1)");

	// identity fallback warns
	spec.labelValues.clear();
	const LabelMap identity = buildLabelMap(spec, &warning);
	CHECK(identity.identity && warning.find("labels.values") != std::string::npos,
	      "missing label table falls back to raw class indices with a warning");
	const std::vector<int> raw = mapClassIndicesToLabels(labels, identity);
	CHECK(raw == labels, "identity mapping keeps the raw class indices");

	// out-of-range class index fails loudly instead of corrupting the output
	bool threw = false;
	try
	{
		mapClassIndicesToLabels({0, 9}, labelMap);
	}
	catch (const std::exception&)
	{
		threw = true;
	}
	CHECK(threw, "class index outside the label map throws");
}

// ---------------------------------------------------------------------------
// 3b. named color scale + the colorbar legend rendering path
// ---------------------------------------------------------------------------
//! Rebuilds the exact ramp-row sampling of ccRenderingTools::DrawColorRamp's
//! custom-labels path (the legend spans the tick values; the bottom row
//! samples the smallest one; sf->getColor samples through the SF's
//! steps-based quantization with the scale's getColorByValue as the
//! out-of-range fallback) and checks that every class's tick row resolves
//! to that class's exact palette color - including class 0 at the bottom
//! and the last class at the top (which a left-anchored band layout can
//! never reach) - in every case: fully named classes, a cloud without any
//! class-0 point, the alwaysShowZero flag, and a label table whose first
//! class carries no name (its text-less tick must keep the span complete -
//! a missing first tick starts the bar at the SECOND class's color and
//! clips the first class's band off).
static void testClassColorScaleLegend()
{
	LabelMap labelMap;
	labelMap.values = {1, 2, 3, 4, 5, 6, 7, 8, 9};
	labelMap.names  = {"ground",
	                   "building",
	                   "pole-road_sign-traffic_light",
	                   "bollard-small_pole",
	                   "trash_can",
	                   "barrier",
	                   "pedestrian",
	                   "car",
	                   "natural-vegetation"};

	ccColorScale::Shared scale = classColorScale(labelMap, 9);
	CHECK(scale != nullptr, "named color scale: built for a fully named label table");
	CHECK(scale->customLabels().size() == 9, "named color scale: one tick per class");
	CHECK(scale->customLabels().begin()->value == 1.0, "named color scale: the first tick is class 0's dataset label");
	CHECK(scale->customLabels().begin()->text == QString("ground"), "named color scale: the first tick carries the class name");

	// color comparison with a small tolerance (the scale interpolates in
	// float and truncates back to 8-bit components)
	const auto sameColor = [](const ccColor::Rgb& a, const ccColor::Rgb& b)
	{
		return std::abs(static_cast<int>(a.r) - static_cast<int>(b.r)) <= 2 && std::abs(static_cast<int>(a.g) - static_cast<int>(b.g)) <= 2 && std::abs(static_cast<int>(a.b) - static_cast<int>(b.b)) <= 2;
	};
	// which class palette color a color is (-1 = no class color, e.g. grey);
	// the bound covers every class count used below (palette hues are
	// pairwise distinct for indices this far apart, so no false matches)
	const auto bandIndexOf = [&sameColor](const ccColorScale::Shared& colorScale, const ccColor::Rgb& c)
	{
		for (int k = 0; k < 16; ++k)
		{
			if (sameColor(c, paletteColor(k)))
			{
				return k;
			}
		}
		return -1;
	};

	// the relative position of each class's tick (k/8 for labels 1..9)
	// resolves to exactly that class's palette color: the centered band
	// layout puts the tick in the middle of its solid region, far from the
	// quantization error of the steps-based sampling (this covers both
	// endpoints - class 0 at 0.0 and the last class at 1.0)
	for (int k = 0; k < 9; ++k)
	{
		CHECK(bandIndexOf(scale, *scale->getColorByRelativePos(k / 8.0)) == k,
		      "scale: the relative position of each class tick shows that class's color");
	}

	// the exact row color of a legend row (sf->getColor, then the scale's
	// own getColorByValue as the out-of-display-range fallback, exactly as
	// DrawColorRamp does for custom labels)
	const auto rowColor = [&scale](const ccScalarField::Shared& field, double value)
	{
		const ccColor::Rgb* col = field->getColor(static_cast<ScalarType>(value));
		if (!col)
		{
			col = scale->getColorByValue(value, &ccColor::lightGreyRGB);
		}
		return col ? *col : ccColor::Rgb(0, 0, 0);
	};
	const auto rowBand = [&scale, &bandIndexOf, &rowColor](const ccScalarField::Shared& field, double value)
	{
		return bandIndexOf(scale, rowColor(field, value));
	};

	ccScalarField::Shared sf(new ccScalarField("SemSeg.label"));
	CHECK(sf->resizeSafe(9), "legend: label scalar field created");
	for (unsigned i = 0; i < 9; ++i)
	{
		sf->setValue(i, static_cast<ScalarType>(i + 1));
	}
	sf->computeMinAndMax();
	// the plugin disables the NaN-grey before attaching the scale so that
	// out-of-display-range legend rows (classes the cloud has no point of)
	// fall through to the scale's own mapping instead of a light grey
	sf->showNaNValuesInGrey(false);
	sf->setColorScale(scale);

	const double front    = scale->customLabels().begin()->value; // 1 (ground)
	const double maxRange = scale->customLabels().rbegin()->value - front;
	const int    H        = 320;
	const auto   rowValue = [&](int j)
	{ return front + (j * maxRange) / H; };

	CHECK(rowBand(sf, rowValue(0)) == 0, "legend: the bottom row of the colorbar is class 0's color (bright red)");
	CHECK(rowBand(sf, rowValue(H)) == 8, "legend: the top row of the colorbar is the last class's color");
	CHECK(rowBand(sf, rowValue(H / 8 + 1)) == 1, "legend: rows above the second class's tick are class 1's color");
	// every class's tick row shows exactly that class's color (the centered
	// band layout keeps the tick in the middle of its solid region, away
	// from the ~1/256 quantization error of the steps-based sampling)
	bool ticksOk = true;
	for (int k = 0; k < 9; ++k)
	{
		ticksOk = ticksOk && rowBand(sf, 1.0 + k) == k;
	}
	CHECK(ticksOk, "legend: every class's tick row shows that class's color");
	// rows a tenth of a label unit off a tick stay in the same solid band
	// (the band edges sit half a unit away; endpoints clamped to the scale)
	bool nearTicksOk = true;
	for (int k = 0; k < 9; ++k)
	{
		if (k > 0)
		{
			nearTicksOk = nearTicksOk && rowBand(sf, 1.0 + k - 0.1) == k;
		}
		if (k < 8)
		{
			nearTicksOk = nearTicksOk && rowBand(sf, 1.0 + k + 0.1) == k;
		}
	}
	CHECK(nearTicksOk, "legend: rows just around each tick stay in that class's band");
	// the rows at the band boundaries (the midpoints between two ticks -
	// real legend rows for labels 1..9) render a CLASS color, never a
	// blend garbage value
	CHECK(bandIndexOf(scale, rowColor(sf, 1.5)) >= 0, "legend: the row at a band boundary renders a class color (no blend garbage)");
	CHECK(bandIndexOf(scale, rowColor(sf, 2.5)) >= 0, "legend: the second boundary row also renders a class color");

	// a cloud without any class-0 point: the legend must still span ALL
	// classes (the custom-labels path ignores the SF content for the span)
	// with class 0's band at the bottom via the out-of-range fallback
	ccScalarField::Shared sfNoGround(new ccScalarField("SemSeg.label (2)"));
	CHECK(sfNoGround->resizeSafe(8), "legend: scalar field without class 0 created");
	for (unsigned i = 0; i < 8; ++i)
	{
		sfNoGround->setValue(i, static_cast<ScalarType>(i + 2));
	}
	sfNoGround->computeMinAndMax();
	sfNoGround->showNaNValuesInGrey(false);
	sfNoGround->setColorScale(scale);
	CHECK(rowBand(sfNoGround, rowValue(0)) == 0, "legend: class 0's band stays at the bottom even when the cloud has no class-0 point");
	CHECK(rowBand(sfNoGround, rowValue(H)) == 8, "legend: the top row is unchanged when class 0 is absent");

	// alwaysShowZero inserts a 0 tick: the bar then spans 0..9, and value 0
	// is outside both the SF's range and the scale's own absolute range, so
	// the strip below the first class renders the designed light grey, and
	// the first class's color starts at its own tick (row 36 = the first
	// row at or above value 1 on a 0..9 bar of height H)
	CHECK(sameColor(rowColor(sf, 0.0), ccColor::lightGreyRGB),
	      "legend: with alwaysShowZero the strip below the first class is the designed light grey");
	CHECK(rowBand(sf, 36.0 * 9.0 / H) == 0,
	      "legend: with alwaysShowZero the first class's color starts at its own tick");

	// a class without a name must not lose its band: its text-less tick
	// keeps the legend's span complete
	LabelMap unnamedFirst       = labelMap;
	unnamedFirst.names          = {"",
	                               "building",
	                               "pole-road_sign-traffic_light",
	                               "bollard-small_pole",
	                               "trash_can",
	                               "barrier",
	                               "pedestrian",
	                               "car",
	                               "natural-vegetation"};
	ccColorScale::Shared scale2 = classColorScale(unnamedFirst, 9);
	CHECK(scale2 != nullptr, "unnamed first class: the scale is still built (8 named classes remain)");
	CHECK(scale2->customLabels().size() == 9, "unnamed first class: the text-less first tick keeps the span complete");
	CHECK(scale2->customLabels().begin()->value == 1.0, "unnamed first class: the span still starts at class 0's dataset label");
	CHECK(bandIndexOf(scale2, *scale2->getColorByRelativePos(0.0)) == 0, "unnamed first class: relative position 0 is still class 0's color");

	// no names at all: the default numeric ramp is kept
	LabelMap noNames;
	noNames.values = labelMap.values;
	CHECK(classColorScale(noNames, 9) == nullptr, "no class names: the default numeric ramp is kept");

	// duplicate dataset label values keep the first class's color at the
	// front of the ramp (no NaN texel: regression for the zero-width
	// stop-interval division in ccColorScale::update)
	LabelMap dupLabels;
	dupLabels.values            = {1, 2, 2, 4};
	dupLabels.names             = {"a", "b", "c", "d"};
	ccColorScale::Shared scale3 = classColorScale(dupLabels, 4);
	CHECK(scale3 != nullptr, "duplicate label values: the scale is still built");
	CHECK(bandIndexOf(scale3, *scale3->getColorByRelativePos(0.0)) == 0, "duplicate label values: the first ramp texel is class 0's color (no NaN texel)");
}

