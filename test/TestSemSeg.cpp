	std::vector<char> readBytes(const fs::path& file)
	{
		std::ifstream in(file, std::ios::binary);
		if (!in)
		{
			throw std::runtime_error("cannot open fixture: " + file.string());
		}
		return std::vector<char>(std::istreambuf_iterator<char>(in), std::istreambuf_iterator<char>());
	}

	std::vector<float> readF32(const fs::path& file)
	{
		const std::vector<char> bytes = readBytes(file);
		if (bytes.size() % sizeof(float) != 0)
		{
			throw std::runtime_error("fixture size is not a multiple of 4: " + file.string());
		}
		std::vector<float> out(bytes.size() / sizeof(float));
		std::memcpy(out.data(), bytes.data(), bytes.size());
		return out;
	}

	std::vector<int64_t> readI64(const fs::path& file)
	{
		const std::vector<char> bytes = readBytes(file);
		if (bytes.size() % sizeof(int64_t) != 0)
		{
			throw std::runtime_error("fixture size is not a multiple of 8: " + file.string());
		}
		std::vector<int64_t> out(bytes.size() / sizeof(int64_t));
		std::memcpy(out.data(), bytes.data(), bytes.size());
		return out;
	}

	std::vector<int32_t> readI32(const fs::path& file)
	{
		const std::vector<char> bytes = readBytes(file);
		if (bytes.size() % sizeof(int32_t) != 0)
		{
			throw std::runtime_error("fixture size is not a multiple of 4: " + file.string());
		}
		std::vector<int32_t> out(bytes.size() / sizeof(int32_t));
		std::memcpy(out.data(), bytes.data(), bytes.size());
		return out;
	}

	size_t approxEqual(const std::vector<float>& a, const std::vector<float>& b, double tolerance)
	{
		if (a.size() != b.size())
		{
			return 1; // count as one mismatch
		}
		size_t bad = 0;
		for (size_t i = 0; i < a.size(); i++)
		{
			if (std::abs(static_cast<double>(a[i]) - b[i]) > tolerance)
			{
				++bad;
			}
		}
		return bad;
	}

	//! Lexicographic row sort (for order-independent comparisons of point sets)
	std::vector<float> sortedRows(const std::vector<float>& pts)
	{
		const size_t        n = pts.size() / 3;
		std::vector<size_t> order(n);
		for (size_t i = 0; i < n; i++)
		{
			order[i] = i;
		}
		std::sort(order.begin(), order.end(), [&](size_t a, size_t b)
		          {
			for (int d = 0; d < 3; d++)
			{
				const float va = pts[a * 3 + d];
				const float vb = pts[b * 3 + d];
				if (va != vb)
				{
					return va < vb;
				}
			}
			return false; });
		std::vector<float> out(pts.size());
		for (size_t i = 0; i < n; i++)
		{
			std::memcpy(out.data() + i * 3, pts.data() + order[i] * 3, 3 * sizeof(float));
		}
		return out;
	}
