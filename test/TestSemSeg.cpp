// Parity tests for the qSemSeg inference pipeline against the Python
// reference (Open3D-ML src/onnx/infer_onnx.py). The golden arrays in test/data
// are generated by make_fixture.py, which drives the REAL reference pipeline
// (grid subsampling, patch sampling, eval augmentation, FPS hierarchy, float64
// softmax accumulation). RNG streams cannot be matched across numpy and C++,
// so every randomness-dependent value (patch indices, FPS starts) is recorded
// in the fixtures and fed to the C++ side.
//
// Test groups:
//   1. tensor parity  - preprocessing (voxel barycenters + projection) and the
//                       full per-patch ONNX input set (points, features, sp0..3,
//                       idx0..13) byte-for-byte against the reference
//   2. output decoding - float64 softmax + smooth accumulation + argmax vs the
//                       reference values
//   3. point-to-label mapping - proj_inds back-mapping and the class->dataset
//                       label mapping (OutputMapper)
//   4. manifest loading + model/cloud compatibility validation
//
// Optional "run" mode (not run by ctest): compares the plugin-built inputs for
// the REAL model against reference logits. See validate_run().

