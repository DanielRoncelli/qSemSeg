static void testGuards()
{
	// memory estimate: m x C x 4 bytes
	CHECK(testProbsMemoryBytes(1000, 9) == 1000.0 * 9 * 4, "guards: testProbs memory estimate is m*C*4");
	CHECK(testProbsMemoryBytes(0, 9) == 0.0, "guards: zero-point estimate is 0");

	std::string error;
	CHECK(checkTestProbsMemory(1000, 9, 2.0 * 1024 * 1024 * 1024, &error), "guards: memory guard passes under the limit");
	CHECK(error.empty(), "guards: no error message when the guard passes");
	CHECK(!checkTestProbsMemory(700000000, 9, 2.0 * 1024 * 1024 * 1024, &error), "guards: memory guard trips above the limit");
	CHECK(error.find("voxel") != std::string::npos, "guards: memory error suggests raising the voxel size");
	CHECK(error.find("GB") != std::string::npos, "guards: memory error names the required size");
	CHECK(checkTestProbsMemory(700000000, 9, 1e12, nullptr), "guards: a custom limit can lift the guard");
	CHECK(checkTestProbsMemory(1, 1, 4.0, &error), "guards: the guard passes at exactly the limit");

	std::vector<float> finite{1.f, -2.5f, 0.f};
	CHECK(allFinite(finite.data(), finite.size()), "guards: allFinite accepts finite values");
	std::vector<float> withNaN{1.f, std::numeric_limits<float>::quiet_NaN()};
	CHECK(!allFinite(withNaN.data(), withNaN.size()), "guards: allFinite detects NaN");
	std::vector<float> withInf{1.f, std::numeric_limits<float>::infinity()};
	CHECK(!allFinite(withInf.data(), withInf.size()), "guards: allFinite detects Inf");
	std::vector<float> leadingNaN{std::numeric_limits<float>::quiet_NaN(), 1.f};
	CHECK(!allFinite(leadingNaN.data(), leadingNaN.size()), "guards: allFinite detects a leading NaN");
	CHECK(allFinite(nullptr, 0), "guards: allFinite on an empty range is true");

	// ORT allocation-failure hint (the classic case: a huge patch size OOMs a
	// ReduceMax working buffer - observed with a user-raised patch size)
	const std::string ortOOM      = "Non-zero status code returned while running ReduceMax node. "
	                                "Status Message: ... Failed to allocate memory for requested buffer of size 8589934592";
	const std::string oomWithHint = "Run failed: " + ortOOM + allocationFailureHint("Run failed: " + ortOOM);
	CHECK(oomWithHint.find("hint:") != std::string::npos, "guards: allocation failures get an actionable hint");
	CHECK(oomWithHint.find("batch size") != std::string::npos && oomWithHint.find("points-per-patch") != std::string::npos, "guards: the hint names the memory drivers (patch points, batch size)");
	CHECK(allocationFailureHint("Run failed: Invalid input shape").empty(), "guards: non-allocation errors get no hint");

	// calibration failure note
	CHECK(calibrationFailureNote({}, 1, "").empty(), "guards: no calibration note without failed candidates");
	const std::string note = calibrationFailureNote({8}, 4, "Run failed: ... Failed to allocate memory ...");
	CHECK(note.find("8") != std::string::npos && note.find("batch size 4") != std::string::npos, "guards: the note names the failed and the chosen batch sizes");
	CHECK(note.find("[E:onnxruntime]") != std::string::npos, "guards: the note explains the ORT log line");
	CHECK(note.find("Failed to allocate memory") != std::string::npos, "guards: the note keeps the original error");

	// execution-provider helpers (the Auto-selection logic relies on them)
	CHECK(isGpuExecutionProvider("CUDAExecutionProvider"), "providers: CUDA is a GPU provider");
	CHECK(isGpuExecutionProvider("DmlExecutionProvider"), "providers: DirectML is a GPU provider");
	CHECK((!isGpuExecutionProvider("CPUExecutionProvider")), "providers: the CPU is not a GPU provider");
	CHECK(providerDisplayName("CPUExecutionProvider") == "CPU", "providers: CPU display name");
	CHECK(providerDisplayName("CUDAExecutionProvider") == "CUDA (NVIDIA GPU)", "providers: CUDA display name");
	CHECK(providerDisplayName("DmlExecutionProvider") == "DirectML (any DX12 GPU)", "providers: DirectML display name");
	CHECK(providerDisplayName("AcmeExecutionProvider") == "AcmeExecutionProvider", "providers: unknown ids are returned unchanged");
}

//! Real-model warm-up probe test (needs an ORT library + a model; skipped
//! otherwise - see the optional ctest arguments in test/CMakeLists.txt)
static void testWarmupProbe(const std::string& ortPath, const std::string& modelPath)
{
	OrtLibrary&                    ortLibrary = OrtLibrary::instance();
	std::string                    ortError;
	const std::vector<std::string> ortPaths = ortPath.empty() ? std::vector<std::string>{} : std::vector<std::string>{ortPath};
	if (!ortLibrary.load(ortPaths, &ortError))
	{
		std::printf("SKIP (warm-up probe): ONNX Runtime not loadable: %s\n", ortError.c_str());
		return;
	}
	OrtSession  session;
	std::string sessionError;
	if (!session.create(modelPath, {"CPUExecutionProvider"}, &sessionError))
	{
		CHECK(false, (std::string("warm-up probe: session creation failed: ") + sessionError).c_str());
		return;
	}

	ModelSpec spec = loadModelSpec(QString::fromStdString(modelPath), nullptr);
	fillSpecFromSession(spec, session);
	std::string ioError = validateSpecAgainstIO(spec, readIOContract(session));
	CHECK(ioError.empty(), (std::string("warm-up probe: spec validated against the real IO (") + ioError + ")").c_str());

	// runtime capability query (the Auto-selection authority): the provider
	// the session runs on must be listed by the loaded runtime
	{
		const std::vector<std::string> available = availableExecutionProviders();
		bool                           hasCpu    = false;
		bool                           hasActive = false;
		for (const std::string& p : available)
		{
			hasCpu    = hasCpu || p == "CPUExecutionProvider";
			hasActive = hasActive || p == session.activeProvider();
		}
		CHECK(!available.empty(), "runtime providers: the loaded ONNX Runtime lists its execution providers");
		CHECK(hasCpu, "runtime providers: the CPU provider is always listed");
		CHECK(hasActive, "runtime providers: the active provider is listed by the runtime");
		CHECK(isGpuExecutionProvider("DmlExecutionProvider") && isGpuExecutionProvider("CUDAExecutionProvider"), "runtime providers: CUDA and DirectML count as GPU providers");
		CHECK((!isGpuExecutionProvider("CPUExecutionProvider")), "runtime providers: the CPU is not a GPU provider");
		CHECK(providerDisplayName("DmlExecutionProvider") == "DirectML (any DX12 GPU)", "runtime providers: DirectML has a display name");
	}

	std::string probeError;
	CHECK(probeSession(session, spec, &probeError), (std::string("warm-up probe: one zero-input forward pass succeeds (") + probeError + ")").c_str());

	// re-creating the session on the same object (the plugin's CPU fallback
	// after a provider produced NaN/Inf) must not duplicate the IO vectors and
	// must keep working
	{
		const size_t inputCount  = session.inputNames.size();
		const size_t outputCount = session.outputNames.size();
		std::string  recreateError;
		CHECK(session.create(modelPath, {"CPUExecutionProvider"}, &recreateError), (std::string("session re-creation succeeds (") + recreateError + ")").c_str());
		CHECK((session.inputNames.size() == inputCount && session.outputNames.size() == outputCount), "session re-creation does not duplicate the IO contract");
		CHECK(session.activeProvider() == "CPUExecutionProvider", "re-created session reports the CPU provider");
		ModelSpec recreated = loadModelSpec(QString::fromStdString(modelPath), nullptr);
		fillSpecFromSession(recreated, session);
		CHECK(validateSpecAgainstIO(recreated, readIOContract(session)).empty(), "re-created session still validates against the spec");
	}

	// negative: a spec without session IO information cannot be probed
	ModelSpec   emptySpec;
	std::string emptyError;
	CHECK(!probeSession(session, emptySpec, &emptyError), "warm-up probe: a spec without session IO fails");
	CHECK(!emptyError.empty(), "warm-up probe: the empty-IO failure carries a message");

	// batch-size calibration on the live session
	std::string batchError;
	const int   autoBatch = autoSelectBatchSize(session, spec, &batchError);
	CHECK(autoBatch >= 1 && autoBatch <= 32, (std::string("batch calibration: size within [1, 32] (got ") + std::to_string(autoBatch) + ")").c_str());
	CHECK(autoSelectBatchSize(session, emptySpec, &batchError) == 1, "batch calibration: empty IO falls back to 1");
}

//! Model validation report with a real runtime + model (needs both optional
//! ctest args): the report creates a CPU session and checks the IO contract
static void testValidationReportSession(const std::string& ortPath, const std::string& modelPath)
{
	std::string                    ortError;
	const std::vector<std::string> ortPaths = {ortPath};
	if (!OrtLibrary::instance().load(ortPaths, &ortError))
	{
		std::printf("SKIP (validation report session test): ONNX Runtime not loadable: %s\n", ortError.c_str());
		return;
	}

	// which cloud features the model demands decides the negative check: the
	// real Open3D-ML test model uses feature_mode 'irgb' (a cloud without
	// colors/intensity fails the report), the committed tiny CI model is
	// plain 'xyz' (any cloud passes)
	QString         specWarning;
	const ModelSpec spec                 = loadModelSpec(QString::fromStdString(modelPath), &specWarning);
	const bool      needsColorsIntensity = (spec.featureMode == "irgb" || spec.featureMode == "i_rgb"
                                       || spec.featureMode == "intensity_rgb" || spec.featureMode == "rgb_i");

	// happy path: a cloud WITH colors and intensity satisfies the model; the
	// report creates a CPU session and validates the manifest against the
	// real graph IO contract
	QString report;
	CHECK(buildModelValidationReport(QString::fromStdString(modelPath), true, true, report), "validation session: the model passes every check");
	CHECK(report.contains("PASSED"), "validation session: the report headline says PASSED");
	CHECK(report.contains("the graph IO contract matches the manifest"), "validation session: the IO contract was checked against the real graph");
	CHECK(report.contains("model architecture"), "validation session: the model architecture is resolved");
	CHECK(report.contains("ONNX Runtime"), "validation session: the runtime status is in the report");

	if (needsColorsIntensity)
	{
		// negative: without colors/intensity the feature check fails the report
		QString missingReport;
		CHECK((!buildModelValidationReport(QString::fromStdString(modelPath), false, false, missingReport)), "validation session: a cloud without the required features fails the report");
		CHECK(missingReport.contains("FAILED"), "validation session: the feature-failure headline");
	}
	else
	{
		// plain-xyz model: even a featureless cloud satisfies the feature check
		QString bareReport;
		CHECK(buildModelValidationReport(QString::fromStdString(modelPath), false, false, bareReport), "validation session: a plain-xyz model accepts a featureless cloud");
	}
}

