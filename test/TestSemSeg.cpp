// fs::path -> QString: path::value_type is wchar_t on Windows but char on
// Linux/macOS, so the conversion needs one helper instead of a Windows-only
// QString::fromWCharArray(p.c_str()) at every call site.
static QString qpath(const fs::path& p)
{
#ifdef _WIN32
	return QString::fromWCharArray(p.c_str());
#else
	return QString::fromStdString(p.string());
#endif
}

static int s_failures = 0;
static int s_checks   = 0;

#define CHECK(cond, message) \
	do \
	{ \
		++s_checks; \
		if (!(cond)) \
		{ \
			++s_failures; \
			std::fprintf(stderr, "FAIL: %s\n", (message)); \
			std::fflush(stderr); \
		} \
	} while (false)

