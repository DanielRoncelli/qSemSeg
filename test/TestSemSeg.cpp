// ---------------------------------------------------------------------------
// 6d. subsampling menu (T12): none / random / fps + manifest parsing
// ---------------------------------------------------------------------------
static void testSubsamplingModes()
{
	// synthetic cloud: 3x5x7 grid = 105 distinct points
	std::vector<float> xyz;
	for (int x = 0; x < 3; x++)
	{
		for (int y = 0; y < 5; y++)
		{
			for (int z = 0; z < 7; z++)
			{
				xyz.push_back(static_cast<float>(x));
				xyz.push_back(static_cast<float>(y));
				xyz.push_back(static_cast<float>(z));
			}
		}
	}
	const size_t n = xyz.size() / 3;

	// none: everything is kept, projection is the identity
	{
		SubsamplingParams p;
		p.type       = ModelSpec::SubsamplingType::None;
		CloudPre pre = preprocessCloud(xyz, {}, {}, {}, 0.08, false, p);
		CHECK((pre.M == n && pre.subPoints == xyz), "subsampling none keeps every point");
		bool identity = pre.projInds.size() == n;
		for (size_t i = 0; identity && i < n; i++)
		{
			identity = pre.projInds[i] == static_cast<int64_t>(i);
		}
		CHECK(identity, "subsampling none has an identity projection map");
	}
	// random: exact target count, subset of the ORIGINAL points, deterministic
	{
		SubsamplingParams p;
		p.type   = ModelSpec::SubsamplingType::Random;
		p.target = 40;
		std::mt19937_64 rng1(12345);
		p.rng      = &rng1;
		CloudPre a = preprocessCloud(xyz, {}, {}, {}, 0.08, false, p);
		CHECK(a.M == 40, "subsampling random keeps the target count");
		// every selected point is an original point (multiset check via sorting)
		std::vector<std::array<float, 3>> aPts(40);
		for (size_t i = 0; i < 40; i++)
		{
			aPts[i] = {a.subPoints[i * 3], a.subPoints[i * 3 + 1], a.subPoints[i * 3 + 2]};
		}
		std::sort(aPts.begin(), aPts.end());
		bool allOriginal = std::unique(aPts.begin(), aPts.end()) == aPts.end();
		for (const auto& pt : aPts)
		{
			allOriginal = allOriginal && pt[0] >= 0 && pt[0] <= 2 && pt[1] >= 0 && pt[1] <= 4 && pt[2] >= 0 && pt[2] <= 6;
		}
		CHECK(allOriginal, "subsampling random picks distinct original points");
		std::mt19937_64 rng2(12345);
		p.rng      = &rng2;
		CloudPre b = preprocessCloud(xyz, {}, {}, {}, 0.08, false, p);
		CHECK(b.subPoints == a.subPoints, "subsampling random is deterministic for the same seed");
		// projection: selected points map exactly to their own subset position
		// (coords unique -> exactly `target` originals self-project); every
		// projection stays in range even for unselected originals
		bool inRange = a.projInds.size() == n;
		for (size_t i = 0; inRange && i < n; i++)
		{
			inRange = a.projInds[i] >= 0 && a.projInds[i] < static_cast<int64_t>(a.M);
		}
		CHECK(inRange, "subsampling random keeps every projection in range");
		size_t exact = 0;
		for (size_t i = 0; i < n; i++)
		{
			const int64_t o = a.projInds[i];
			exact += (a.subPoints[o * 3] == xyz[i * 3] && a.subPoints[o * 3 + 1] == xyz[i * 3 + 1] && a.subPoints[o * 3 + 2] == xyz[i * 3 + 2]) ? 1 : 0;
		}
		CHECK(exact == 40, "subsampling random self-projects exactly the selected originals");
	}
	// fps: exact target count, deterministic, identity projection
	{
		SubsamplingParams p;
		p.type   = ModelSpec::SubsamplingType::Fps;
		p.target = 25;
		std::mt19937_64 rng1(777);
		p.rng      = &rng1;
		CloudPre a = preprocessCloud(xyz, {}, {}, {}, 0.08, false, p);
		CHECK(a.M == 25, "subsampling fps keeps the target count");
		std::mt19937_64 rng2(777);
		p.rng      = &rng2;
		CloudPre b = preprocessCloud(xyz, {}, {}, {}, 0.08, false, p);
		CHECK(b.subPoints == a.subPoints, "subsampling fps is deterministic for the same seed");
		size_t exact = 0;
		for (size_t i = 0; i < n; i++)
		{
			const int64_t o = a.projInds[i];
			exact += (a.subPoints[o * 3] == xyz[i * 3] && a.subPoints[o * 3 + 1] == xyz[i * 3 + 1] && a.subPoints[o * 3 + 2] == xyz[i * 3 + 2]) ? 1 : 0;
		}
		CHECK(exact == 25, "subsampling fps self-projects exactly the selected originals");
	}
	// features are gathered alongside the points for the subset modes
	{
		std::vector<float> intensity(n);
		for (size_t i = 0; i < n; i++)
		{
			intensity[i] = static_cast<float>(i); // intensity == original index
		}
		SubsamplingParams p;
		p.type   = ModelSpec::SubsamplingType::Random;
		p.target = 10;
		std::mt19937_64 rng(42);
		p.rng        = &rng;
		CloudPre pre = preprocessCloud(xyz, {}, intensity, {}, 0.08, false, p);
		bool     ok  = pre.subIntensity.size() == 10;
		for (size_t o = 0; ok && o < 10; o++)
		{
			// find the original index by coords (unique grid): the gathered
			// intensity must be that index's intensity
			size_t origIdx = n;
			for (size_t i = 0; i < n; i++)
			{
				if (pre.subPoints[o * 3] == xyz[i * 3] && pre.subPoints[o * 3 + 1] == xyz[i * 3 + 1] && pre.subPoints[o * 3 + 2] == xyz[i * 3 + 2])
				{
					origIdx = i;
					break;
				}
			}
			ok = origIdx < n && pre.subIntensity[o] == intensity[origIdx];
		}
		CHECK(ok, "subsampling random gathers the feature channels of the selected points");
	}
	// misused parameters are loud errors (the manifest parser prevents this upstream)
	{
		SubsamplingParams p;
		p.type     = ModelSpec::SubsamplingType::Random;
		p.target   = 0;
		bool threw = false;
		try
		{
			preprocessCloud(xyz, {}, {}, {}, 0.08, false, p);
		}
		catch (const std::exception&)
		{
			threw = true;
		}
		CHECK(threw, "random subsampling without a target throws");
	}
	// manifest parsing: subsampling.type + target, warnings on gaps
	{
		ModelSpec spec;
		applyEmbeddedJsonToSpec(spec, R"({"preprocessing":{"subsampling":{"type":"random","target":5000}}})", nullptr);
		CHECK((spec.subsamplingType == ModelSpec::SubsamplingType::Random && spec.subsamplingTarget == 5000), "manifest subsampling random+target is parsed");
	}
	{
		ModelSpec spec;
		applyEmbeddedJsonToSpec(spec, R"({"preprocessing":{"subsampling":{"type":"none"}}})", nullptr);
		CHECK(spec.subsamplingType == ModelSpec::SubsamplingType::None, "manifest subsampling none is parsed");
	}
	// fps without a target warns and falls back to none (sidecar path)
	{
		QTemporaryDir dir;
		CHECK(dir.isValid(), "temp dir for the subsampling sidecar");
		const QString modelPath = dir.filePath(QStringLiteral("model.onnx"));
		{
			QFile f(modelPath + QStringLiteral(".meta.json"));
			CHECK(f.open(QIODevice::WriteOnly), "write the subsampling sidecar fixture");
			f.write(R"({"preprocessing":{"subsampling":{"type":"fps"}}})");
		}
		QString   warning;
		ModelSpec spec = loadModelSpec(modelPath, &warning);
		CHECK((spec.subsamplingType == ModelSpec::SubsamplingType::None && warning.contains(QStringLiteral("target"))), "fps without a target warns and falls back to none");
	}
	{
		QTemporaryDir dir;
		CHECK(dir.isValid(), "temp dir for the subsampling sidecar (unknown type)");
		const QString modelPath = dir.filePath(QStringLiteral("model.onnx"));
		{
			QFile f(modelPath + QStringLiteral(".meta.json"));
			CHECK(f.open(QIODevice::WriteOnly), "write the unknown-type sidecar fixture");
			f.write(R"({"preprocessing":{"subsampling":{"type":"magic"}}})");
		}
		QString   warning;
		ModelSpec spec = loadModelSpec(modelPath, &warning);
		CHECK((spec.subsamplingType == ModelSpec::SubsamplingType::Voxel && warning.contains(QStringLiteral("unknown subsampling.type"))), "an unknown subsampling type warns and keeps voxel");
	}
}

