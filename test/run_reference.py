"""Runs the REAL reference pipeline on the parity fixture and dumps golden logits.

Loads the arrays that make_fixture.py wrote (Python-ordered subsampled cloud,
reference-sampled patch indices, recorded FPS start indices), rebuilds the ONNX
inputs with the reference adapter - the exact build_patch_inputs path used to
generate the fixture, with the FPS start indices replayed so the support
points match the fixture - then runs the converted model with onnxruntime
(CPU) and dumps main_logits.f32 / main_labels_golden.i32 next to the fixture.

TestSemSeg run <dataDir> <model.onnx> then compares the C++-built inputs'
logits against this dump (input construction parity end-to-end).

    python run_reference.py --onnx /path/to/fkaconv_parislille3d.onnx

--prefix selects the basename of the golden files (default "main"). The tiny
CI model (test/data/tiny_fkaconv.onnx, generated by make_tiny_model.py) shares
the main fixture inputs, so its goldens are written alongside them:
    python run_reference.py --onnx test/data/tiny_fkaconv.onnx --prefix tiny
"""

import argparse
import os
import sys
from pathlib import Path

import numpy as np


def read_f32(path):
    return np.fromfile(path, dtype='<f4')


def read_i64(path):
    return np.fromfile(path, dtype='<i8')


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--open3dml-src', dest='open3dml_src', default=os.environ.get('OPEN3DML_SRC', ''), help='path to the Open3D-ML src/ directory (or set OPEN3DML_SRC)')
    parser.add_argument('--data-dir', default=str(Path(__file__).resolve().parent / 'data'))
    parser.add_argument('--onnx', default=os.environ.get('OPEN3DML_MODEL', ''), help='path to the ONNX model (or set OPEN3DML_MODEL)')
    parser.add_argument('--prefix', default='main',
                        help='basename of the golden files to write: <prefix>_logits.f32 '
                             'and <prefix>_labels_golden.i32 ("main" = real parity model, '
                             '"tiny" = the committed tiny CI model)')
    args = parser.parse_args()

    sys.path.insert(0, args.open3dml_src)
    sys.path.insert(0, str(Path(args.open3dml_src) / 'onnx'))

    import onnxruntime as ort
    from onnx_common import build_adapter, build_model, load_config

    data_dir = Path(args.data_dir)

    cfg = load_config('fkaconv_parislille3d.yml')
    cfg.model['in_channels'] = 3
    cfg.model['feature_mode'] = 'xyz'
    model = build_model(cfg, seed=42)
    adapter = build_adapter(model, in_channels=3)

    sub_points = read_f32(data_dir / 'main_sub_points.f32').reshape(-1, 3)
    idxs = read_i64(data_dir / 'main_idxs.i64')
    starts = read_i64(data_dir / 'main_fps_start.i64').tolist()

    class ReplayRng:
        """Replays the recorded FPS start indices in draw order (one
        rng.integers(0, n) draw per FPS invocation, exactly what
        FKAConv._farthest_point_sample consumes). Shared across every FPS
        call of the hierarchy, so stage s gets the s-th recorded start."""

        def __init__(self, values):
            self.values = list(values)
            self.i = 0

        def integers(self, low, high=None):
            v = self.values[self.i % len(self.values)]
            self.i += 1
            return v

    import models.fkaconv as fkaconv_mod
    original_fps = fkaconv_mod._farthest_point_sample
    replay_rng = ReplayRng(starts)

    def replayed_fps(points, n_samples, rng):
        return original_fps(points, n_samples, replay_rng)

    # pre: the minimal dict build_patch_inputs consumes (fixture sub_points are
    # the reference Python-ordered barycenters; the model needs no extra feat)
    pre = {'sub_points': sub_points, 'sub_feat': None}
    fkaconv_mod._farthest_point_sample = replayed_fps
    try:
        inputs = adapter.build_patch_inputs(pre, idxs, np.random.default_rng(7), 3)
    finally:
        fkaconv_mod._farthest_point_sample = original_fps

    sess = ort.InferenceSession(args.onnx, providers=['CPUExecutionProvider'])
    input_names = [i.name for i in sess.get_inputs()]
    missing = [n for n in input_names if n not in inputs]
    if missing:
        raise SystemExit(f'model inputs missing from the reference build: {missing}')
    logits = sess.run([o.name for o in sess.get_outputs()],
                      {n: inputs[n] for n in input_names})[0]
    logits = np.asarray(logits).reshape(-1, logits.shape[-1]).astype(np.float32)
    labels = np.argmax(logits, axis=1).astype(np.int32)
    print('logits', logits.shape, 'unique labels', np.unique(labels).tolist())

    logits.tofile(data_dir / f'{args.prefix}_logits.f32')
    labels.tofile(data_dir / f'{args.prefix}_labels_golden.i32')
    print(f'wrote {data_dir / (args.prefix + "_logits.f32")} and {args.prefix}_labels_golden.i32')


if __name__ == '__main__':
    main()
